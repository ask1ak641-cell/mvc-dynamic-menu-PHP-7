        $thRows = '';
        foreach ($this->displayColumns as $col) {
            $colLabel = ucwords(str_replace('_', ' ', $col));
            $thRows .= "                            <th>{$colLabel}</th>\n";
        }

        // Build table body
        $tdRows = '';
        foreach ($this->displayColumns as $col) {
            $tdRows .= "                            <td><?= htmlspecialchars(\$row['{$col}']) ?></td>\n";
        }

        $indexCode = <<<PHP
<?php
/**
 * View: {$label} - Index
 */
\$pageTitle = \$title ?? '{$label}';
?>

<!-- Flash message -->
<?php if (\$msg = Session::getFlash('success')): ?>
    <script>window._toastr_success = '<?= addslashes(\$msg) ?>';</script>
<?php endif; ?>
<?php if (\$msg = Session::getFlash('error')): ?>
    <script>window._toastr_error = '<?= addslashes(\$msg) ?>';</script>
<?php endif; ?>

<div class="content-header">
    <div class="container-fluid">
        <div class="row mb-2">
            <div class="col-sm-6">
                <h1 class="m-0"><?= \$pageTitle ?></h1>
