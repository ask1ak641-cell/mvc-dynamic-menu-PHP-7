                    <li class="breadcrumb-item"><a href="<?= URL::base('/dashboard') ?>">Dashboard</a></li>
                    <li class="breadcrumb-item active"><?= \$pageTitle ?></li>
                </ol>
            </div>
        </div>
    </div>
</div>

<div class="content">
    <div class="container-fluid">
        <div class="card">
            <div class="card-header">
                <h3 class="card-title">Daftar {$label}</h3>
                <div class="card-tools">
                    <a href="<?= URL::base('/{$name}/create') ?>" class="btn btn-primary btn-sm">
                        <i class="fas fa-plus"></i> Tambah Data
                    </a>
                </div>
            </div>
            <div class="card-body">
                <!-- Search -->
                <form method="GET" action="<?= URL::base('/{$name}') ?>" class="mb-3">
                    <div class="input-group input-group-sm" style="max-width:300px;">
                        <input type="text" name="search" class="form-control" placeholder="Cari..."
                               value="<?= htmlspecialchars(\$search ?? '') ?>">
                        <div class="input-group-append">
                            <button type="submit" class="btn btn-default"><i class="fas fa-search"></i></button>
                        </div>
                    </div>
                </form>

                <div class="table-responsive">
                    <table class="table table-bordered table-striped table-hover">
                        <thead class="thead-dark">
                            <tr>
                                <th width="50">No</th>
{$thRows}
                                <th width="150">Aksi</th>
                            </tr>
                        </thead>
                        <tbody>
                            <?php if (empty(\$data)): ?>
                            <tr>
                                <td colspan="99" class="text-center text-muted py-3">
                                    <i class="fas fa-inbox fa-2x d-block mb-2"></i>
                                    Belum ada data. Klik "Tambah Data" untuk memulai.
                                </td>
                            </tr>
                            <?php else: ?>
                            <?php \$no = (\$pagination['page'] - 1) * \$pagination['per_page'] + 1; ?>
                            <?php foreach (\$data as \$row): ?>
                            <tr>
                                <td><?= \$no++ ?></td>
{$tdRows}
                                <td>
                                    <a href="<?= URL::base('/{$name}/edit/' . \$row['id']) ?>"
                                       class="btn btn-warning btn-xs" title="Edit">
                                        <i class="fas fa-edit"></i>
                                    </a>
                                    <a href="<?= URL::base('/{$name}/delete/' . \$row['id']) ?>"
                                       class="btn btn-danger btn-xs"
                                       onclick="return confirm('Yakin ingin menghapus data ini?')"
                                       title="Hapus">
                                        <i class="fas fa-trash"></i>
                                    </a>
                                </td>
                            </tr>
                            <?php endforeach; ?>
                            <?php endif; ?>
                        </tbody>
                    </table>
                </div>

                <!-- Pagination -->
                <?php if ((\$pagination['total_pages'] ?? 1) > 1): ?>
                <nav>
                    <ul class="pagination pagination-sm justify-content-center">
                        <?php for (\$i = 1; \$i <= \$pagination['total_pages']; \$i++): ?>
                        <li class="page-item <?= \$i == \$pagination['page'] ? 'active' : '' ?>">
                            <a class="page-link" href="?page=<?= \$i ?>&search=<?= urlencode(\$search ?? '') ?>">
                                <?= \$i ?>
                            </a>
                        </li>
                        <?php endfor; ?>
                    </ul>
                </nav>
                <?php endif; ?>
            </div>
        </div>
    </div>
</div>
PHP;
        $paths[] = $viewDir . '/index.php';
        file_put_contents($viewDir . '/index.php', $indexCode);

        // ─── Create View ─────────────────────────────
        $formFields = $this->buildFormFields();
        
        $createCode = <<<PHP
<?php
/**
 * View: {$label} - Create
 */
\$pageTitle = \$title ?? 'Tambah {$label}';
?>

<div class="content-header">
    <div class="container-fluid">
