                <div class="card-body">
                    <?= Security::csrfField() ?>
{$editFormFields}
                </div>
                <div class="card-footer">
                    <button type="submit" class="btn btn-primary">
                        <i class="fas fa-save"></i> Update
                    </button>
                    <a href="<?= URL::base('/{$name}') ?>" class="btn btn-default">Batal</a>
                </div>
            </form>
