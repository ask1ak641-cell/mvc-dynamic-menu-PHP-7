PHP;
        $paths[] = $viewDir . '/create.php';
        file_put_contents($viewDir . '/create.php', $createCode);

        // ─── Edit View ──────────────────────────────
        $editFormFields = $this->buildFormFields(true);
        
        $editCode = <<<PHP
<?php
/**
 * View: {$label} - Edit
 */
\$pageTitle = \$title ?? 'Edit {$label}';
?>

<div class="content-header">
    <div class="container-fluid">
        <div class="row mb-2">
            <div class="col-sm-6">
                <h1 class="m-0"><?= \$pageTitle ?></h1>
            </div>
            <div class="col-sm-6">
                <ol class="breadcrumb float-sm-right">
