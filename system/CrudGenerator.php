<?php
/**
 * ═══════════════════════════════════════════════════════════════
 *  CRUD Generator - Generate Controller, Model, View otomatis
 * ═══════════════════════════════════════════════════════════════
 * 
 * Cara pakai:
 *   $gen = new CrudGenerator();
 *   $gen->setName('produk')->setFields([...])->generate();
 */
class CrudGenerator
{
    /** @var string */
    private $name;
    /** @var string */
    private $table;
    /** @var string */
    private $label;
    /** @var array */
    private $fields = [];
    /** @var array */
    private $displayColumns = [];

    /**
     * Set nama modul
     */
    public function setName($name)
    {
        $this->name  = strtolower($name);
        $this->table = $this->name;
        $this->label = ucwords(str_replace('_', ' ', $name));
        return $this;
    }

    /**
     * Set nama tabel (bila berbeda dari nama modul)
     */
    public function setTable($table)
    {
        $this->table = $table;
        return $this;
    }

    /**
     * Set label tampilan
     */
    public function setLabel($label)
    {
        $this->label = $label;
        return $this;
    }

    /**
     * Set field definitions
     * 
     * Format per field:
     * [
     *   'name'     => 'nama_kolom',
     *   'label'    => 'Label Kolom',
     *   'type'     => 'text|number|email|textarea|select|date|file',
     *   'required' => true/false,
     *   'options'  => [['value'=>'','label'=>'Pilih']] // untuk type select
     * ]
     */
    public function setFields(array $fields)
    {
        $this->fields = $fields;
        // Auto-set display columns (semua field kecuali password, id, dsb)
        $this->displayColumns = [];
        foreach ($fields as $f) {
            $type = $f['type'] ?? 'text';
            if (!in_array($type, ['password', 'hidden', 'file'])) {
                $this->displayColumns[] = $f['name'];
            }
        }
        return $this;
    }

    /**
     * Jalankan generate semua file
     */
    public function generate(): array
    {
        $results = [];

        // 1. Generate Model
        $results['model'] = $this->generateModel();

        // 2. Generate Controller
        $results['controller'] = $this->generateController();

        // 3. Generate Views (index, create, edit)
        $results['views'] = $this->generateViews();

        // 4. Generate SQL (opsional, untuk referensi)
        $results['sql'] = $this->generateSql();

        return $results;
    }

    /**
     * Generate file Model
     */
    private function generateModel(): string
    {
        $className = ucfirst($this->name);
        $code = <<<PHP
<?php
/**
 * Model: {$this->label}
 * Auto-generated by CRUD Generator
 */
class {$className} extends BaseModel
{
    protected \$table = '{$this->table}';
    protected \$primaryKey = 'id';
}
PHP;

        $path = APP_DIR . "/models/{$className}.php";
        file_put_contents($path, $code);
        return $path;
    }

    /**
     * Generate file Controller
     */
    private function generateController(): string
    {
        $className   = ucfirst($this->name) . 'Controller';
        $modelName   = ucfirst($this->name);
        $modelVar    = lcfirst($modelName);
        $name        = $this->name;
        $label       = $this->label;
        $table       = $this->table;

        // Build field list untuk validasi
        $requiredFields = [];
        $fieldNames     = [];
        foreach ($this->fields as $f) {
            $fieldNames[] = $f['name'];
            if (($f['required'] ?? false) && ($f['type'] ?? 'text') !== 'password') {
                $requiredFields[] = $f['name'];
            }
        }
        $fieldList    = "'" . implode("', '", $fieldNames) . "'";
        $requiredList = "'" . implode("', '", $requiredFields) . "'";

        $code = <<<PHP
<?php
/**
 * Controller: {$label}
 * Auto-generated by CRUD Generator
 */
class {$className} extends BaseController
{
    private {$modelName} \${$modelVar};

    public function __construct()
    {
        // Cek login & akses role
        AuthMiddleware::handle('admin,operator');

        \$this->{$modelVar} = new {$modelName}();
    }

    /**
     * Halaman index / list data
     */
    public function index(): void
    {
        \$page  = (int) (\$_GET['page'] ?? 1);
        \$search = \$this->query('search', '');

        if (\$search) {
            // Cari di semua field tekstual (sederhana)
            \$where = '';
            \$params = [];
            \$conditions = [];
            foreach ([{$fieldList}] as \$field) {
                \$conditions[] = "\`{\$field}\` LIKE ?";
                \$params[] = "%{\$search}%";
            }
            \$where = implode(' OR ', \$conditions);
            \$result = \$this->{$modelVar}->paginate(\$page, 10, \$where, \$params);
        } else {
            \$result = \$this->{$modelVar}->paginate(\$page, 10);
        }

        \$this->view('{$name}/index', [
            'title'      => '{$label}',
            'data'       => \$result['data'],
            'pagination' => \$result,
            'search'     => \$search,
        ]);
    }

    /**
     * Form tambah data
     */
    public function create(): void
    {
        \$this->view('{$name}/create', [
            'title'  => 'Tambah {$label}',
            'fields' => {$modelName}::fields(),
        ]);
    }

    /**
     * Simpan data baru
     */
    public function store(): void
    {
        if (!\$this->isPost()) \$this->redirect('/{$name}/create');

        \$this->validateCsrf();

        \$data = [];
        foreach ([{$fieldList}] as \$field) {
            \$data[\$field] = \$this->input(\$field);
        }

        \$this->{$modelVar}->insert(\$data);

        Session::setFlash('success', 'Data berhasil ditambahkan!');
        \$this->redirect('/{$name}');
    }

    /**
     * Form edit data
     */
    public function edit(\$id): void
    {
        \$data = \$this->{$modelVar}->find(\$id);
        if (!\$data) {
            Session::setFlash('error', 'Data tidak ditemukan.');
            \$this->redirect('/{$name}');
        }

        \$this->view('{$name}/edit', [
            'title'  => 'Edit {$label}',
            'row'    => \$data,
            'fields' => {$modelName}::fields(),
        ]);
    }

    /**
     * Update data
     */
    public function update(\$id): void
    {
        if (!\$this->isPost()) \$this->redirect("/{$name}/edit/{\$id}");

        \$this->validateCsrf();

        \$data = [];
        foreach ([{$fieldList}] as \$field) {
            \$data[\$field] = \$this->input(\$field);
        }

        \$this->{$modelVar}->update(\$id, \$data);

        Session::setFlash('success', 'Data berhasil diupdate!');
        \$this->redirect('/{$name}');
    }

    /**
     * Hapus data
     */
    public function delete(\$id): void
    {
        \$this->{$modelVar}->delete(\$id);
        Session::setFlash('success', 'Data berhasil dihapus!');
        \$this->redirect('/{$name}');
    }
}
PHP;

        $path = APP_DIR . "/controllers/{$className}.php";
        file_put_contents($path, $code);
        return $path;
    }

    /**
     * Generate file View (index, create, edit)
